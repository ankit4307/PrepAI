"""PDF report of one interview session (reportlab)."""

import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def _t(value):
    """Escape for Paragraph and drop characters the built-in PDF font cannot draw (emoji etc.)."""
    text = str(value if value is not None else "")
    text = text.encode("latin-1", "replace").decode("latin-1")
    return escape(text)


def build_session_pdf(user_name, session_row, answers):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm,
                            title="PrepAI Interview Report", author="PrepAI")
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], textColor=colors.HexColor("#084298"), fontSize=20)
    h2 = ParagraphStyle("h2", parent=styles["Heading3"], textColor=colors.HexColor("#0d6efd"), spaceBefore=10)
    body = ParagraphStyle("b", parent=styles["BodyText"], fontSize=10, leading=14)
    small = ParagraphStyle("s", parent=body, fontSize=9, textColor=colors.HexColor("#555555"))

    avg = session_row["average_score"]
    story = [
        Paragraph("PrepAI - Interview Report", h1),
        Paragraph(f"<b>Student:</b> {_t(user_name)}", body),
        Paragraph(
            f"<b>Type:</b> {_t(session_row['interview_type'])} &nbsp; "
            f"<b>Role:</b> {_t(session_row['role'] or '-')} &nbsp; "
            f"<b>Date:</b> {_t(session_row['created_at'])}", body),
        Spacer(1, 6),
    ]

    summary = Table(
        [["Overall score", f"{avg if avg is not None else '-'} / 10", "Questions", str(len(answers))]],
        colWidths=[35 * mm, 35 * mm, 30 * mm, 30 * mm])
    summary.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5ff")),
        ("BOX", (0, 0), (-1, -1), 0.6, colors.HexColor("#0d6efd")),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story += [summary, Spacer(1, 6), HRFlowable(width="100%", color=colors.HexColor("#cfd8ee"))]

    for i, a in enumerate(answers, 1):
        fb = a["feedback"] or {}
        score = a["score"] if a["score"] is not None else "-"
        story.append(Paragraph(f"Q{i}. {_t(a['question'])} &nbsp;&nbsp;<font color='#0d6efd'>[{score}/10]</font>", h2))
        story.append(Paragraph(f"<b>Your answer:</b> {_t(a['answer'])}", body))
        if fb.get("strengths"):
            story.append(Paragraph("<b>What was good:</b> " + _t("; ".join(fb["strengths"])), body))
        if fb.get("improvements"):
            story.append(Paragraph("<b>What to improve:</b> " + _t("; ".join(fb["improvements"])), body))
        if fb.get("sample_answer"):
            story.append(Paragraph("<b>Better sample answer:</b> " + _t(fb["sample_answer"]), body))
        meta = []
        if a.get("time_sec"):
            meta.append(f"Time: {a['time_sec']}s")
        if fb.get("fillers"):
            meta.append(f"Filler words: {fb['fillers']}")
        if meta:
            story.append(Paragraph(" | ".join(meta), small))

    story += [Spacer(1, 12), Paragraph("Generated by PrepAI - AI Interview &amp; Smart Placement Preparation System", small)]
    doc.build(story)
    return buffer.getvalue()
