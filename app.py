@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        full_name = request.form.get("full_name", "").strip()
        email = request.form.get("email", "").strip().lower()
        college = request.form.get("college", "").strip()
        course = request.form.get("course", "").strip()
        graduation_year = request.form.get("graduation_year", "").strip()
        password = request.form.get("password", "")
        confirm_password = request.form.get("confirm_password", "")

        error = None
        if not full_name:
            error = "Full name is required."
        elif not EMAIL_RE.match(email):
            error = "Please enter a valid email address."
        elif not graduation_year.isdigit() or not (2000 <= int(graduation_year) <= 2100):
            error = "Please enter a valid graduation year."
        elif len(password) < 8:
            error = "Password must be at least 8 characters long."
        elif password != confirm_password:
            error = "Passwords do not match!"

        if error:
            return render_template("register.html", error=error)

        connection = get_db_connection()
        existing_user = connection.execute(
            "SELECT id FROM users WHERE lower(email) = ?", (email,)
        ).fetchone()
        if existing_user:
            connection.close()
            return render_template("register.html", error="This email is already registered!")

        connection.execute(
            """
            INSERT INTO users (full_name, email, college, course, graduation_year, password)
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            (full_name[:100], email, college[:150], course[:100], int(graduation_year),
             generate_password_hash(password)),
        )
        connection.commit()
        connection.close()
        return render_template("register.html", success="Registration successful! You can now login.")

    return render_template("register.html")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")
        throttle_key = (request.remote_addr, email)

        if too_many_logins(throttle_key):
            return render_template(
                "login.html", error="Too many failed attempts. Please wait 10 minutes."), 429

        connection = get_db_connection()
        user = connection.execute(
            "SELECT * FROM users WHERE lower(email) = ?", (email,)
        ).fetchone()
        connection.close()

        if user and check_password_hash(user["password"], password):
            _failed_logins.pop(throttle_key, None)
            session.clear()  # prevents session fixation
            session["user_id"] = user["id"]
            session["user_name"] = user["full_name"]
            return redirect(url_for("dashboard"))

        _failed_logins[throttle_key].append(time.time())
        return render_template("login.html", error="Invalid email or password!")

    return render_template("login.html")


