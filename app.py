_calls = defaultdict(deque)
RATE_LIMIT_CALLS = 40      # max AI calls ...
RATE_LIMIT_WINDOW = 600    # ... per 10 minutes per user


def rate_limited(user_id):
    now = time.time()
    q = _calls[user_id]
    while q and now - q[0] > RATE_LIMIT_WINDOW:
        q.popleft()
    if len(q) >= RATE_LIMIT_CALLS:
        return True
    q.append(now)
    return False


_failed_logins = defaultdict(deque)
LOGIN_MAX_FAILS = 5
LOGIN_WINDOW = 600


def too_many_logins(key):
    now = time.time()
    q = _failed_logins[key]
    while q and now - q[0] > LOGIN_WINDOW:
        q.popleft()
    return len(q) >= LOGIN_MAX_FAILS


