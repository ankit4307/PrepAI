def load_session_detail(connection, session_id, user_id):
    """Return (session_row, answers) for a session owned by user_id, otherwise (None, [])."""
    owner = connection.execute(
        "SELECT * FROM interview_sessions WHERE id = ? AND user_id = ?", (session_id, user_id)
    ).fetchone()
    if not owner:
        return None, []
    rows = connection.execute(
        "SELECT question, answer, score, feedback, time_sec FROM interview_answers "
        "WHERE session_id = ? ORDER BY id", (session_id,)).fetchall()
    answers = []
    for r in rows:
        try:
            fb = json.loads(r["feedback"] or "{}")
        except ValueError:
            fb = {}
        answers.append({"question": r["question"], "answer": r["answer"], "score": r["score"],
                        "feedback": fb, "time_sec": r["time_sec"]})
    return owner, answers


