FALLBACK_QUESTIONS = {
    "Technical": list(offline.CONCEPTS.keys()),
    "HR": [
        "Tell me about yourself.",
        "What are your greatest strengths and weaknesses?",
        "Why do you want to work for our company?",
        "Describe a time you worked in a team and faced a conflict.",
        "Where do you see yourself in five years?",
        "Why should we hire you?",
        "Tell me about a challenge you faced and how you solved it.",
        "How do you handle pressure and tight deadlines?",
        "Describe a project you are most proud of.",
        "How do you handle failure or criticism?",
        "What motivates you to work hard?",
        "Are you comfortable relocating or working in shifts?",
    ],
}
FALLBACK_QUESTIONS["Mixed"] = FALLBACK_QUESTIONS["Technical"][:3] + FALLBACK_QUESTIONS["HR"][:2]
VALID_TYPES = set(FALLBACK_QUESTIONS)


def pick_fallback(interview_type):
    """Random questions each time, so the interview never repeats."""
    tech, hr_q = FALLBACK_QUESTIONS["Technical"], FALLBACK_QUESTIONS["HR"]
    if interview_type == "Technical":
        return random.sample(tech, 5)
    if interview_type == "HR":
        return random.sample(hr_q, 5)
    return random.sample(tech, 3) + random.sample(hr_q, 2)


