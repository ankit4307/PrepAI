@app.route("/api/generate-questions", methods=["POST"])
@api_login_required
def generate_questions():
    data = request.get_json(silent=True) or {}
    interview_type = data.get("interview_type", "Technical")
    difficulty = data.get("difficulty", "Medium")
    if interview_type not in VALID_TYPES:
        return jsonify(error="Invalid interview type."), 400
    if difficulty not in VALID_DIFFICULTY:
        return jsonify(error="Invalid difficulty."), 400

    fallback = {"questions": pick_fallback(interview_type), "personalized": False}
    if not ai.ai_enabled():
        return jsonify(fallback)

    connection = get_db_connection()
    profile_row = connection.execute(
        "SELECT skills, projects, target_role FROM student_profiles WHERE user_id = ?",
        (session["user_id"],),
    ).fetchone()
    recent_rows = connection.execute(
        """
        SELECT a.question FROM interview_answers a
        JOIN interview_sessions s ON s.id = a.session_id
        WHERE s.user_id = ? ORDER BY a.id DESC LIMIT 20
        """, (session["user_id"],)).fetchall()
    connection.close()

    role = (str(data.get("role") or "") or (profile_row["target_role"] if profile_row else "")
            or "Software Developer")[:100]
    skills = profile_row["skills"] if profile_row and profile_row["skills"] else "not provided"
    projects = profile_row["projects"] if profile_row and profile_row["projects"] else "not provided"
    recent = "\n".join("- " + r["question"] for r in recent_rows) or "none"
    focus = random.choice(["core concepts", "practical scenarios", "problem solving",
                           "project-based questions", "real-world applications"])

    if rate_limited(session["user_id"]):
        return jsonify(fallback)

    kind_hint = {
        "Technical": "all technical",
        "HR": "all HR / behavioural",
        "Mixed": "3 technical and 2 HR / behavioural",
    }[interview_type]

    prompt = f"""
You are an interviewer preparing a campus placement mock interview.

Candidate target role: {role}
Candidate skills: {skills}
Candidate projects: {projects}

Difficulty: {difficulty} (Easy = basic definitions, Medium = concepts + small scenarios,
Hard = deeper reasoning, trade-offs and problem solving).
Focus this time on: {focus}.
Do NOT repeat or rephrase any of these previously asked questions:
{recent}

Create exactly 5 interview questions ({kind_hint}). Technical questions must
relate to the candidate's skills/projects and suit a fresher. Order them from
easier to harder. Each question must be one clear sentence.

Return ONLY a JSON array of 5 strings. No explanation, no markdown.
"""

    cache_key = (session["user_id"], interview_type, difficulty, role, skills, projects)
    late = _late_questions.pop(cache_key, None)
    if late:
        return jsonify(questions=late, personalized=True)

    def clean_questions(text):
        qs = [str(q).strip() for q in ai.parse_json(text) if str(q).strip()][:5]
        if len(qs) < 3:
            raise ValueError("too few questions")
        return qs

    started = time.time()
    future = _executor.submit(ai.ask_gemini, prompt)
    try:
        questions = clean_questions(future.result(timeout=QUESTION_TIMEOUT))
        app.logger.info("Questions generated in %.1fs", time.time() - started)
        return jsonify(questions=questions, personalized=True)
    except FutureTimeout:
        app.logger.warning("Gemini too slow (>%ss) - using ready-made questions", QUESTION_TIMEOUT)

        def save_late(done):
            try:
                _late_questions[cache_key] = clean_questions(done.result())
            except Exception:
                pass

        future.add_done_callback(save_late)
        return jsonify(fallback)
    except Exception as exc:  # network error, quota, bad JSON ...
        app.logger.warning("Question generation failed: %s", exc)
        return jsonify(fallback)


