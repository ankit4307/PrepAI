def compute_streak(day_strings):
    """Number of consecutive days (ending today or yesterday) with at least one interview."""
    days = set()
    for value in day_strings:
        try:
            days.add(datetime.strptime(value[:10], "%Y-%m-%d").date())
        except (TypeError, ValueError):
            continue
    if not days:
        return 0
    cursor = date.today() if date.today() in days else date.today() - timedelta(days=1)
    streak = 0
    while cursor in days:
        streak += 1
        cursor -= timedelta(days=1)
    return streak


