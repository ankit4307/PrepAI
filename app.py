def extract_resume_text(upload):
    """Read text out of an uploaded PDF / TXT file. Raises ValueError with a friendly message."""
    name = (upload.filename or "").lower()
    raw = upload.read(RESUME_MAX_BYTES + 1)
    if len(raw) > RESUME_MAX_BYTES:
        raise ValueError("File is too large (max 2 MB).")
    if name.endswith(".pdf"):
        try:
            from pypdf import PdfReader
            reader = PdfReader(io.BytesIO(raw))
            pages = reader.pages[:6]
            text = "\n".join((page.extract_text() or "") for page in pages)
        except Exception:
            raise ValueError("Could not read this PDF. Try pasting the resume text instead.")
        if len(text.strip()) < 50:
            raise ValueError("No text found in the PDF (is it a scanned image?). Paste the text instead.")
        return text
    if name.endswith(".txt"):
        return raw.decode("utf-8", errors="ignore")
    raise ValueError("Please upload a PDF or TXT file, or paste your resume text.")


